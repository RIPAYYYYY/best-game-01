// A tiny seeded random number generator (mulberry32). The whole garden grows from one
// seed, so a run — and every staged screenshot — is exactly reproducible.

/** Create a generator from a numeric seed. Same seed, same stream, every time. */
export function createRng(seed) {
  let state = (seed >>> 0) || 1;
  function next() {
    state = (state + 0x6d2b79f5) >>> 0;
    let t = state;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  }
  return {
    next,
    /** A float in [min, max). */
    range(min, max) {
      return min + next() * (max - min);
    },
    /** An integer in [min, max], both ends included. */
    int(min, max) {
      return min + Math.floor(next() * (max - min + 1));
    },
    /** True with probability p. */
    chance(p) {
      return next() < p;
    },
    /** One element of the array, chosen by the stream. */
    pick(items) {
      return items[Math.floor(next() * items.length)];
    },
  };
}
